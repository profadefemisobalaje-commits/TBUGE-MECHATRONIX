def cmd_scaffold(args) -> int:
    data = load_outline()
    courses = all_courses(data)
    if args.course:
        courses = [c for c in courses if c["number"] == args.course]
        if not courses:
            print(f"no course numbered {args.course}", file=sys.stderr)
            return 1
    made = 0
    for course in courses:
        d = course_dir(course)
        d.mkdir(parents=True, exist_ok=True)
        for i, title in enumerate(course["chapters"], start=1):
            p = chapter_path(course, i, title)
            if p.exists() and not args.force:
                continue
            p.write_text(
                SKELETON.format(
                    title=title,
                    cnum=course["number"],
                    cnum2=i,
                    coursetitle=course["title"],
                ),
                encoding="utf-8",
            )
            made += 1
    print(f"created {made} chapter file(s) under book/courses")
    return 0


# ---------------------------------------------------------------- status

def command_status(args) -> int:
    data = load_outline()
    target = args.target or data["book"]["target_words_per_course"]
    courses = all_courses(data)
    rows, total, done_courses = [], 0, 0
    for course in courses:
        d = course_dir(course)
        files = sorted(d.glob("*.md")) if d.exists() else []
        chapters = [f for f in files if f.name.startswith("chapter-")]
        wc = sum(len(words(p.read_text(encoding="utf-8"))) for p in files)
        total += wc
        ok = wc >= target
        done_courses += ok
        state = "PASS" if ok else "...."
        rows.append(
            f"{course['number']:>2}. {course['title'][:44]:<44} "
            f"{len(chapters):>2}/10 ch  {wc:>7,} / {target:,}  {100 * wc / target:>5.0f}%  {state}"
        )
    print("\n".join(rows))
    print("-" * 92)
    print(
        f"{'TOTAL':<4}{'':<44}      {total:>7,} words   "
        f"{done_courses}/{len(courses)} courses at target   "
        f"{100 * total / (target * len(courses)):.1f}% of the book"
    )
    return 0


# ---------------------------------------------------------------- style

BAD_PHRASES = {
    "utilize": "use",
    "utilise": "use",
    "leverage": "use",
    "in order to": "to",
    "it should be noted that": "(delete)",
    "it is important to note that": "(delete)",
    "a number of": "some",
    "in the event that": "if",
    "prior to": "before",
    "subsequently": "then",
    "hereby": "(delete)",
    "whilst": "while",
    "commence": "start",
    "terminate": "end",
    "ascertain": "find out",
    "endeavour": "try",
    "facilitate": "help",
    "demonstrate": "show",
    "approximately": "about",
    "sufficient": "enough",
    "numerous": "many",
}


def cmd_style(args) -> int:
    problems = 0
    for name in args.paths:
        p = Path(name)
        text = p.read_text(encoding="utf-8")
        wc = len(words(text))
        sents = sentences(text)
        if not sents:
            print(f"{p.name}: no prose found")
            continue
        lengths = [len(s.split()) for s in sents]
        avg = sum(lengths) / len(lengths)
        long_s = [s for s in sents if len(s.split()) > 30]
        paras = [x for x in prose(text).split("\n") if x.strip()]
        print(f"\n{name}")
        print(f"  words            {wc:,}")
        print(f"  sentences        {len(sents)}")
        print(f"  average length   {avg:.1f} words  (target 14-20)")
        print(f"  over 30 words    {len(long_s)}  (target 0)")
        up = sum(1 for w in words(text) if w.isupper() and len(w) > 2)
        print(f"  shouts           {up} ALL-CAPS words (target 0)")
        hits = []
        low = strip_markdown(text).lower()
        for bad, better in BAD_PHRASES.items():
            n = len(re.findall(r"\b" + re.escape(bad) + r"\b", low))
            if n:
                hits.append(f"'{bad}' x{n} -> '{better}'")
        print(f"  wordiness        {len(hits)} issue(s)")
        for h in hits:
            print(f"    - {h}")
        if long_s:
            print("  longest sentence:")
            print("   ", max(long_s, key=lambda s: len(s.split()))[:260])
        problems += len(long_s) + len(hits) + up
    return 1 if problems and args.strict else 0


# ---------------------------------------------------------------- build

def cmd_build(_args) -> int:
    data = load_outline()
    parts = []
    for name in ["00-front-matter.md", "01-table-of-contents.md"]:
        p = BOOK / name
        if p.exists():
            parts.append(p.read_text(encoding="utf-8"))
    for course in all_courses(data):
        d = course_dir(course)
        if not d.exists():
            continue
        files = sorted(d.glob("chapter-*.md"))
        if not files:
            continue
        parts.append(f"\n\n# Course {course['number']}: {course['title']}\n")
        for f in files:
            parts.append(f.read_text(encoding="utf-8"))
    out = BOOK / "Artificial-Intelligence-and-Robotics.md"
    out.write_text("\n\n---\n\n".join(parts), encoding="utf-8")
    print(f"wrote {out.relative_to(ROOT)} ({len(words(out.read_text(encoding='utf-8'))):,} words)")
    return 0


# ---------------------------------------------------------------- main

def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = ap.add_subparsers(dest="cmd", required=True)

    sub.add_parser("toc").set_defaults(func=cmd_toc)

    s = sub.add_parser("scaffold")
    s.add_argument("--course", type=int, help="only this course number")
    s.add_argument("--force", action="store_true", help="overwrite existing files")
    s.set_defaults(func=cmd_scaffold)

    s = sub.add_parser("status")
    s.add_argument("--target", type=int, help="words required per course (default from outline)")
    s.set_defaults(func=command_status)

    s = sub.add_parser("style")
    s.add_argument("paths", nargs="+")
    s.add_argument("--strict", action="store_true", help="exit 1 if any issue is found")
    s.set_defaults(func=cmd_style)

    sub.add_parser("build").set_defaults(func=cmd_build)

    args = ap.parse_args()
    return args.func(args)


if __name__ == "__main__":
    sys.exit(main())
