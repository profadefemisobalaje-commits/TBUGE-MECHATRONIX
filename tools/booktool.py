#!/usr/bin/env python3
"""Small toolkit for building "Artificial Intelligence and Robotics".

Commands
--------
  toc                      regenerate book/01-table-of-contents.md from outline.json
  scaffold [--course N]    create empty course folders + chapter files from the outline
  status                   word-count report per course and for the whole book
  style PATH [PATH ...]    plain-English checks on one or more chapter files
  build                    stitch the whole book into one Markdown file

Run from anywhere: python3 tools/booktool.py status
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
BOOK = ROOT / "book"
COURSES = BOOK / "courses"
OUTLINE = BOOK / "outline.json"

# ---------------------------------------------------------------- helpers

def load_outline() -> dict:
    return json.loads(OUTLINE.read_text(encoding="utf-8"))


def all_courses(data: dict) -> list[dict]:
    return [c for y in data["years"] for c in y["courses"]]


def slug(text: str) -> str:
    text = text.lower().replace("&", "and")
    text = re.sub(r"[^a-z0-9]+", "-", text)
    return text.strip("-")


def course_dir(course: dict) -> Path:
    return COURSES / f"course-{course['number']:02d}-{slug(course['title'])}"


def chapter_path(course: dict, index: int, title: str) -> Path:
    return course_dir(course) / f"chapter-{index:02d}-{slug(title)}.md"


def strip_markdown(text: str) -> str:
    text = re.sub(r"```.*?```", " ", text, flags=re.S)      # code blocks
    text = re.sub(r"`[^`]*`", " ", text)                     # inline code
    text = re.sub(r"\[([^\]]*)\]\([^)]*\)", r"\1", text)     # links
    text = re.sub(r"^[#>|]+", " ", text, flags=re.M)         # headings, quotes
    text = re.sub(r"[*_~]", "", text)
    return text


def words(text: str) -> list[str]:
    return re.findall(r"[A-Za-z0-9][A-Za-z0-9'\-]*", strip_markdown(text))


def prose(text: str) -> str:
    """Body text only: no headings, lists, tables, code or front matter."""
    text = re.sub(r"```.*?```", " ", text, flags=re.S)
    lines = []
    for line in text.splitlines():
        s = line.strip()
        if not s or s.startswith(("#", "|", "-", "*", ">", "!", "1.", "2.", "3.",
                                   "4.", "5.", "6.", "7.", "8.", "9.")):
            continue
        lines.append(s)
    return " ".join(lines)


def sentences(text: str) -> list[str]:
    parts = re.split(r"(?<=[.!?])\s+", prose(text))
    return [p for p in parts if len(p.split()) > 1]


# ---------------------------------------------------------------- toc

def cmd_toc(_args) -> int:
    data = load_outline()
    b = data["book"]
    courses = all_courses(data)
    out = [
        "<!-- Generated by tools/booktool.py toc. Edit book/outline.json, not this file. -->",
        "",
        "# Table of Contents",
        "",
        f"*{b['title']}: {b['subtitle']}*",
        "",
        f"The book has **{len(courses)} courses** and **{sum(len(c['chapters']) for c in courses)} chapters**. "
        f"Every course is a self-contained block of about {b['target_words_per_course']:,} words: "
        f"a course introduction, {b['chapters_per_course']} chapters of about "
        f"{b['target_words_per_chapter']:,} words each, and a review with assessment and glossary.",
        "",
        "Each chapter follows the same eight-part shape, so you always know what is coming: "
        "Opening, Big Picture, Key Words, The Explanation, Where It Goes Wrong, Case Note, "
        "Mini-Lab, and Recap and Questions.",
        "",
    ]

    current = None
    for course in courses:
        group = None
        for y in data["years"]:
            if course in y["courses"]:
                group = f"{y['year']} - {y['semester']}"
        if group != current:
            current = group
            out += ["", f"## {group}", ""]
        out += [
            f"### Course {course['number']}: {course['title']}",
            "",
            f"*{course['promise']}*",
            "",
        ]
        for i, title in enumerate(course["chapters"], start=1):
            out.append(f"{i}. {title}")
        out.append("")

    out += [
        "",
        "---",
        "",
        "## Back Matter",
        "",
        "1. Master Glossary (every bold key word in the book, in one place)",
        "2. Formula Sheet (the maths worth remembering, with plain-English notes)",
        "3. Lab and Project Index",
        "4. Answers to Check-Yourself Questions",
        "5. Further Reading, by Course",
        "6. Index",
        "",
    ]
    (BOOK / "01-table-of-contents.md").write_text("\n".join(out), encoding="utf-8")
    print(f"wrote book/01-table-of-contents.md ({len(courses)} courses)")
    return 0


# ---------------------------------------------------------------- scaffold

